/**
 * Returns a guaranteed valid bundled image URL based on input src or category.
 */
export function resolveImageUrl(src?: string | null, category?: string): string {
  if (!src || typeof src !== 'string' || src.trim() === '' || src === '[object Object]') {
    return getCategoryDefaultImage(category);
  }

  const cleanSrc = src.trim();

  // 1. Data URLs and Blob URLs are immediately returned as valid
  if (cleanSrc.startsWith('data:') || cleanSrc.startsWith('blob:')) {
    return cleanSrc;
  }

  // 2. Check if cleanSrc matches a key in IMAGE_MAP directly
  if (IMAGE_MAP[cleanSrc]) {
    return IMAGE_MAP[cleanSrc];
  }

  // 3. Extract filename from paths like `/src/assets/images/filename.jpg` or `../assets/images/filename.jpg`
  const lastSlashIdx = cleanSrc.lastIndexOf('/');
  const filename = lastSlashIdx !== -1 ? cleanSrc.slice(lastSlashIdx + 1) : cleanSrc;

  if (IMAGE_MAP[filename]) {
    return IMAGE_MAP[filename];
  }

  // 4. Fuzzy match based on partial asset names
  const lowerName = filename.toLowerCase();
  for (const [key, val] of Object.entries(IMAGE_MAP)) {
    const keyBase = key.split('_')[0]; // e.g. "kenya" or "coldroom" or "hero"
    if (keyBase.length > 3 && lowerName.includes(keyBase)) {
      return val;
    }
  }

  // 5. If it's a valid remote URL (http/https), return it
  if (cleanSrc.startsWith('http://') || cleanSrc.startsWith('https://')) {
    return cleanSrc;
  }

  // 6. Otherwise fallback to category image
  return getCategoryDefaultImage(category);
}

/**
 * Returns a high quality default bundled image URL based on category context.
 */
export function getCategoryDefaultImage(category?: string): string {
  if (!category) return refrigerationHeroBgImg;
  const cat = category.toLowerCase();

  if (cat.includes('cold') || cat.includes('walkin') || cat.includes('cooler')) {
    return coldRoomBuildImg;
  }
  if (cat.includes('hvac') || cat.includes('ac') || cat.includes('air')) {
    return hvacAcImg;
  }
  if (cat.includes('industrial') || cat.includes('plant') || cat.includes('compressor')) {
    return factoryAfricanImg;
  }
  if (cat.includes('field') || cat.includes('installation') || cat.includes('technician') || cat.includes('team')) {
    return kenyanEngineersImg;
  }
  if (cat.includes('dairy') || cat.includes('milk')) {
    return dairyCoolingImg;
  }
  if (cat.includes('pharma') || cat.includes('chiller')) {
    return pharmaColdchainImg;
  }
  if (cat.includes('fridge') || cat.includes('refrigerator') || cat.includes('freezer')) {
    return fridgeRepairAfImg;
  }
  if (cat.includes('maint') || cat.includes('service') || cat.includes('preventive')) {
    return preventiveMaintImg;
  }
  if (cat.includes('avatar') || cat.includes('user') || cat.includes('testimonial') || cat.includes('author')) {
    return testimonialMale1Img;
  }

  return refrigerationHeroBgImg;
}
